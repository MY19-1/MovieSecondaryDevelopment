package com.util;

public class EmailCodeInfoUtil {
    private String code;
    private long expireTime ;

    public EmailCodeInfoUtil(String code, long expireTime) {
        this.code = code;
        this.expireTime = expireTime;
    }

    public String getCode() {
        return code;
    }

    public void setCode(String code) {
        this.code = code;
    }

    public long getExpireTime() {
        return expireTime;
    }

    public void setExpireTime(long expireTime) {
        this.expireTime = expireTime;
    }
}
